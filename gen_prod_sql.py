#!/usr/bin/env python3
"""
gen_prod_sql.py - turn the flights backfilled into the LOCAL ADSB database into a plain SQL file
that can be run (by a human) on another ADSB database, e.g. production.

Reads (local, via --env-file, default .env) the flight_sector rows enriched on/after --since
together with their track_segment, svl_track_raw, svl_flight_raw, track_event and process_control
rows, and emits one transaction that re-creates them with *new* ids generated by the target
database (flight_sector_id == its track_segment.segment_id, so ids differ from local).

The target's own ADSB functions are NOT used (they assume segments arrive in time order, which
a backfill breaks); prior_segment_id is left NULL (each flight is inserted as a standalone segment).
Nothing existing in the target is modified. The script aborts if a flight already exists.
"""
import argparse
import json
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

from dotenv import load_dotenv
from psycopg.rows import dict_row

import flight_backfill as fb

# flight_sector columns that must start from the target's defaults (Billing / POD bookkeeping)
SECTOR_SKIP = {"pod_updated", "pod_response_data", "pod_updated_at", "pod_retry_count", "public_link",
               "pod_link_sent", "has_synched"}


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, Decimal)):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, (datetime, date)):
        return "'" + v.isoformat() + "'"
    if isinstance(v, (dict, list)):
        v = json.dumps(v, separators=(",", ":"))
    return "'" + str(v).replace("'", "''") + "'"


def cols_of(cur, table):
    cur.execute("select column_name, udt_name from information_schema.columns "
                "where table_schema='flight_tracking' and table_name=%s order by ordinal_position", (table,))
    return [(r["column_name"], r["udt_name"]) for r in cur.fetchall()]


def select_list(cols, skip):
    """geometry columns come back as EWKT text (geometry_in parses it on insert)."""
    out = []
    for name, udt in cols:
        if name in skip:
            continue
        out.append(f"st_asewkt({name}) as {name}" if udt == "geometry" else name)
    return out


def insert_stmt(table, row, extra=None):
    row = {**row, **(extra or {})}
    names = ", ".join(row)
    vals = ", ".join(v if isinstance(v, _Raw) else lit(v) for v in row.values())
    return f"insert into flight_tracking.{table} ({names})\n    values ({vals})"


class _Raw(str):
    """SQL fragment emitted verbatim."""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--env-file", default=".env", help="the LOCAL database to read from")
    ap.add_argument("--since", required=True, metavar="YYYY-MM-DD", help="export flights with fr24_enriched_at on/after this date")
    ap.add_argument("--out", type=Path, default=Path("backfill_to_prod.sql"))
    args = ap.parse_args()
    load_dotenv(args.env_file)

    conn = fb.pg_connect()
    cur = conn.cursor(row_factory=dict_row)
    seg_cols = cols_of(cur, "track_segment")
    sec_cols = cols_of(cur, "flight_sector")
    trk_cols = cols_of(cur, "svl_track_raw")
    ev_cols = cols_of(cur, "track_event")

    cur.execute("select flight_sector_id from flight_tracking.flight_sector "
                "where fr24_call and fr24_enriched_at >= %s order by flight_start_e", (args.since,))
    ids = [r["flight_sector_id"] for r in cur.fetchall()]

    blocks, summary = [], []
    for sid in ids:
        cur.execute(f"select {', '.join(select_list(sec_cols, SECTOR_SKIP | {'flight_sector_id', 'last_segment_id'}))} "
                    "from flight_tracking.flight_sector where flight_sector_id = %s", (sid,))
        sec = cur.fetchone()
        cur.execute(f"select {', '.join(select_list(seg_cols, {'segment_id', 'track_id', 'prior_segment_id'}))}, track_id "
                    "from flight_tracking.track_segment where segment_id = %s", (sid,))
        seg = cur.fetchone()
        old_track = seg.pop("track_id")
        cur.execute(f"select {', '.join(select_list(trk_cols, {'id'}))} from flight_tracking.svl_track_raw where id = %s",
                    (old_track,))
        trk = cur.fetchone()
        cur.execute(f"select {', '.join(select_list(ev_cols, {'track_event_id', 'track_id'}))} "
                    "from flight_tracking.track_event where track_id = %s order by event_begin", (old_track,))
        events = cur.fetchall()
        cur.execute("select icao24, rx_utc, sensor, trust_lvl, trk_state, callsign, mode_a "
                    "from flight_tracking.svl_flight_raw where icao24 = %s and rx_utc = %s", (trk["icao24"], trk["track_end"]))
        fraw = cur.fetchone()
        cur.execute("select last_processed_time, complete from flight_tracking.process_control where track_id = %s", (old_track,))
        pc = cur.fetchone()

        icao, cs = sec["icao24"], (sec["callsign"] or "").strip()
        label = f"{cs} {icao} {datetime.fromtimestamp(sec['flight_start_e']).date()}"
        summary.append(label)
        fs, fe = lit(sec["flight_start_e"]), lit(sec["flight_end_e"])

        b = [f"-- {label}",
             "do $$",
             "declare t_id bigint; s_id bigint;",
             "begin",
             f"  if exists (select 1 from flight_tracking.flight_sector where icao24 = {lit(icao)} and flight_start_e = {fs}) then",
             f"    raise exception 'flight_sector already exists: {label}';",
             "  end if;",
             f"  if exists (select 1 from flight_tracking.svl_track_raw where icao24 = {lit(icao)} and track_start = {lit(trk['track_start'])}) then",
             f"    raise exception 'svl_track_raw already exists: {label}';",
             "  end if;",
             "  " + insert_stmt("svl_track_raw", trk) + "\n    returning id into t_id;",
             "  " + insert_stmt("track_segment", seg, {
                 "track_id": _Raw("t_id"),
                 "prior_segment_id": None,
             }) + "\n    returning segment_id into s_id;",
             "  " + insert_stmt("flight_sector", sec, {"flight_sector_id": _Raw("s_id"), "last_segment_id": _Raw("s_id")}) + ";"]
        for ev in events:
            b.append("  " + insert_stmt("track_event", ev, {"track_id": _Raw("t_id")}) + ";")
        if fraw:
            b.append("  " + insert_stmt("svl_flight_raw", fraw) + "\n    on conflict (icao24, rx_utc) do nothing;")
        if pc:
            b.append("  " + insert_stmt("process_control", pc, {"track_id": _Raw("t_id")}) + ";")
        b.append(f"  insert into _backfill_result values ({lit(cs)}, {lit(icao)}, s_id, t_id);")
        b += ["end", "$$;", ""]
        blocks.append("\n".join(b))

    head = f"""-- Generated by gen_prod_sql.py from the local ADSB database: {len(ids)} flights.
-- Creates svl_track_raw + track_segment + flight_sector (+ track_event, svl_flight_raw, process_control)
-- per flight, with prior_segment_id NULL. New ids come from the target database's own sequences. Existing rows are not modified.
-- Aborts the whole transaction if any flight already exists.
--
--   Review the result below, then run COMMIT; (or ROLLBACK;).

begin;

create temp table _backfill_result (callsign text, icao24 text, flight_sector_id bigint, track_id bigint);

"""
    tail = f"""
-- Review before COMMIT: expect {len(ids)} rows.
select callsign, icao24, flight_sector_id, track_id from _backfill_result order by flight_sector_id;
select count(*) as inserted, {len(ids)} as expected from _backfill_result;

-- commit;   -- <- uncomment (or type COMMIT;) once the rows above look right
-- rollback;
"""
    args.out.write_text(head + "\n".join(blocks) + tail)
    print(f"wrote {args.out}: {len(ids)} flights")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
